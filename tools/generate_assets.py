#!/usr/bin/env python3
"""
Generate compressed boot logo (include/boot_logo.h) and anti-aliased LovyanGFX
VLW smooth fonts (include/ui_fonts.h) for the VESC Wide Display (800x480).

Usage:
    python3 tools/generate_assets.py [--verify-only]

Zero external dependencies beyond Python 3 stdlib + Pillow (PIL).
"""

import io
import os
import re
import struct
import sys
from pathlib import Path
from PIL import Image, ImageFont

ROOT = Path(__file__).resolve().parent.parent
BOOT_LOGO_H = ROOT / "include" / "boot_logo.h"
UI_FONTS_H = ROOT / "include" / "ui_fonts.h"

ROBOTO_BOLD = "/usr/share/fonts/truetype/Roboto-Bold.ttf"
ROBOTO_MEDIUM = "/usr/share/fonts/truetype/Roboto-Medium.ttf"


def format_c_byte_array(data: bytes, indent: str = "    ", cols: int = 16) -> str:
    lines = []
    for i in range(0, len(data), cols):
        chunk = data[i : i + cols]
        lines.append(indent + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    return "\n".join(lines)


# ==============================================================================
# 1. Boot Logo Compression (RGB565 -> Clean Lossless Grayscale PNG)
# ==============================================================================
def extract_boot_logo_image(header_path: Path) -> Image.Image:
    """Read existing boot_logo.h (either legacy RGB565 or already PNG)."""
    text = header_path.read_text(encoding="utf-8")

    # Case A: Already converted to BOOT_LOGO_PNG
    m_png = re.search(r"BOOT_LOGO_PNG\[.*?\]\s*(?:PROGMEM\s*)?=\s*\{(.*?)\};", text, re.S)
    if m_png:
        raw = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m_png.group(1)))
        return Image.open(io.BytesIO(raw)).convert("L")

    # Case B: Legacy raw RGB565 array
    mw = re.search(r"#define\s+BOOT_LOGO_WIDTH\s+(\d+)", text)
    mh = re.search(r"#define\s+BOOT_LOGO_HEIGHT\s+(\d+)", text)
    w = int(mw.group(1)) if mw else 420
    h = int(mh.group(1)) if mh else 180

    m_rgb = re.search(r"boot_logo_rgb565\[.*?\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m_rgb:
        raise RuntimeError(f"Could not find boot_logo_rgb565 or BOOT_LOGO_PNG in {header_path}")

    vals = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m_rgb.group(1))]
    if len(vals) != w * h:
        raise RuntimeError(f"Expected {w * h} RGB565 pixels, got {len(vals)}")

    img = Image.new("L", (w, h))
    px = img.load()
    for i, v in enumerate(vals):
        r = ((v >> 11) & 0x1F) * 255 // 31
        g = ((v >> 5) & 0x3F) * 255 // 63
        b = (v & 0x1F) * 255 // 31
        lum = (r + g + b) // 3
        # Denoise legacy 1-LSB RGB565 quantization speckles while keeping smooth AA edges
        if lum <= 8:
            lum = 0
        elif lum >= 242:
            lum = 255
        px[i % w, i // w] = lum
    return img


def generate_boot_logo(header_path: Path) -> dict:
    orig_header_size = header_path.stat().st_size
    img = extract_boot_logo_image(header_path)
    w, h = img.size

    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True, compress_level=9)
    png_bytes = buf.getvalue()

    # Sanity-verify round-trip decode
    decoded = Image.open(io.BytesIO(png_bytes))
    assert decoded.size == (w, h), f"PNG size mismatch: {decoded.size}"
    assert decoded.mode == "L", f"Expected grayscale PNG, got {decoded.mode}"
    assert list(decoded.tobytes()) == list(img.tobytes()), "PNG round-trip pixel mismatch!"

    content = f"""#pragma once

#include <stdint.h>
#include <stddef.h>
#if defined(ARDUINO)
#include <pgmspace.h>
#elif !defined(PROGMEM)
#define PROGMEM
#endif

// ==============================================================================
// Boot Logo Asset (Lossless 8-bit Grayscale PNG, Pure White on Pure Black)
// Dimensions: {w} x {h} (Aspect ratio preserved, centered on 800x480 screen)
// Compressed size: {len(png_bytes)} bytes ({len(png_bytes) / 1024.0:.2f} KB)
// Generated by tools/generate_assets.py
//
// Usage in LovyanGFX (ESP32-S3 & Native Linux Simulator):
//   int lx = (800 - BOOT_LOGO_WIDTH) / 2;
//   int ly = (480 - BOOT_LOGO_HEIGHT) / 2;
//   _canvas->drawPng(BOOT_LOGO_PNG, BOOT_LOGO_PNG_LEN, lx, ly);
//   _canvas->releasePngMemory(); // Optional: frees ~44 KB pngle scratch buffer
// ==============================================================================
#define BOOT_LOGO_WIDTH    {w}
#define BOOT_LOGO_HEIGHT   {h}
#define BOOT_LOGO_PNG_LEN  {len(png_bytes)}

static const uint8_t BOOT_LOGO_PNG[BOOT_LOGO_PNG_LEN] PROGMEM = {{
{format_c_byte_array(png_bytes)}
}};
"""
    header_path.write_text(content, encoding="utf-8")
    return {
        "width": w,
        "height": h,
        "png_bytes": len(png_bytes),
        "orig_header_bytes": orig_header_size,
        "new_header_bytes": len(content.encode("utf-8")),
    }


# ==============================================================================
# 2. Anti-Aliased LovyanGFX VLW Font Generator & Byte-by-Byte Verifier
# ==============================================================================
def trim_mask(mask_bytes: bytes, w: int, h: int):
    """Trim fully transparent outer rows/columns; return (trimmed_bytes, nw, nh, dx_add, dy_sub)."""
    if w == 0 or h == 0:
        return b"", 0, 0, 0, 0

    rows = [mask_bytes[y * w : (y + 1) * w] for y in range(h)]
    top = 0
    while top < h and not any(rows[top]):
        top += 1
    if top == h:
        return b"", 0, 0, 0, 0

    bottom = h - 1
    while bottom > top and not any(rows[bottom]):
        bottom -= 1

    left = 0
    while left < w and not any(rows[y][left] for y in range(top, bottom + 1)):
        left += 1

    right = w - 1
    while right > left and not any(rows[y][right] for y in range(top, bottom + 1)):
        right -= 1

    nw = right - left + 1
    nh = bottom - top + 1
    out = bytearray()
    for y in range(top, bottom + 1):
        out.extend(rows[y][left : right + 1])
    return bytes(out), nw, nh, left, top


def build_vlw_font(ttf_path: str, px_size: int, chars: list[str], tabular_digits: bool = False) -> dict:
    """
    Build a LovyanGFX-compatible big-endian VLW font binary blob.

    VLW Binary Layout (exact match to LovyanGFX VLWfont::loadFont / drawChar):
      Header (24 bytes = 6 x big-endian uint32):
        [0] gCount     : number of glyphs (strictly sorted ascending by unicode!)
        [1] version    : 11 (Processing VLW v11)
        [2] yAdvance   : maxAscent + maxDescent
        [3] spaceWidth : width of space character (0x20)
        [4] ascent     : maxAscent across ALL included glyphs
        [5] descent    : maxDescent across ALL included glyphs

      Glyph Metric Table (gCount x 28 bytes = 7 x big-endian int32/uint32):
        [0] unicode    : UTF-16 BMP codepoint (uint32, sorted ascending)
        [1] height     : bitmap height in px (uint32)
        [2] width      : bitmap width in px (uint32, <= 255)
        [3] gxAdvance  : horizontal cursor advance in px (uint32, <= 255)
        [4] dY         : signed distance from baseline UP to bitmap top (int32)
        [5] dX         : signed distance from cursor X to bitmap left (int32, -128..127)
        [6] padding    : 0 (uint32)

      Glyph Bitmaps (concatenated in glyph order):
        For each glyph: width * height bytes of 8-bit grayscale alpha (0x00..0xFF).
    """
    font = ImageFont.truetype(ttf_path, px_size)

    # Sort uniquely by Unicode codepoint (CRITICAL: LovyanGFX uses std::lower_bound!)
    codepoints = sorted(set(ord(ch) for ch in chars))
    assert all(0 < cp <= 0xFFFF for cp in codepoints), "VLW supports BMP codepoints 1..0xFFFF only"

    # Optional tabular digit enforcement (ensures zero horizontal jitter on live gauges)
    digit_adv = None
    if tabular_digits:
        digit_advs = [int(round(font.getlength(d))) for d in "0123456789"]
        digit_adv = max(digit_advs)

    glyphs = []
    max_ascent = 0
    max_descent = 0
    space_width = max(1, int(round(font.getlength(" "))))

    for cp in codepoints:
        ch = chr(cp)
        adv = digit_adv if (tabular_digits and "0" <= ch <= "9") else int(round(font.getlength(ch)))
        adv = max(1, min(255, adv))

        if cp == 0x20:
            glyphs.append({
                "unicode": cp,
                "height": 0,
                "width": 0,
                "gxAdvance": adv,
                "dY": 0,
                "dX": 0,
                "bitmap": b"",
            })
            space_width = adv
            continue

        mask, (off_x, off_y) = font.getmask2(ch, mode="L", anchor="ls")
        mw, mh = mask.size
        raw_bmp = bytes(mask)
        bmp, w, h, trim_l, trim_t = trim_mask(raw_bmp, mw, mh)

        if w == 0 or h == 0:
            raise RuntimeError(f"Non-space glyph U+{cp:04X} ('{ch}') produced empty bitmap in {ttf_path}@{px_size}px")

        dx = off_x + trim_l
        dy = -(off_y + trim_t)  # positive = above baseline

        # If tabular digit had narrower natural advance, center within tabular cell
        if tabular_digits and "0" <= ch <= "9":
            nat_adv = int(round(font.getlength(ch)))
            if adv > nat_adv:
                dx += (adv - nat_adv) // 2

        assert 0 <= w <= 255, f"Glyph U+{cp:04X} width {w} exceeds uint8"
        assert 0 <= h <= 255, f"Glyph U+{cp:04X} height {h} exceeds uint8"
        assert -128 <= dx <= 127, f"Glyph U+{cp:04X} dX {dx} exceeds int8"

        max_ascent = max(max_ascent, dy)
        max_descent = max(max_descent, max(0, h - dy))

        glyphs.append({
            "unicode": cp,
            "height": h,
            "width": w,
            "gxAdvance": adv,
            "dY": dy,
            "dX": dx,
            "bitmap": bmp,
        })

    y_advance = max_ascent + max_descent

    # Pack big-endian VLW binary
    out = bytearray()
    out.extend(struct.pack(">IIIIII", len(glyphs), 11, y_advance, space_width, max_ascent, max_descent))

    for g in glyphs:
        out.extend(struct.pack(
            ">IIIIiiI",
            g["unicode"],
            g["height"],
            g["width"],
            g["gxAdvance"],
            g["dY"],
            g["dX"],
            0,
        ))

    for g in glyphs:
        out.extend(g["bitmap"])

    return {
        "data": bytes(out),
        "gCount": len(glyphs),
        "yAdvance": y_advance,
        "spaceWidth": space_width,
        "ascent": max_ascent,
        "descent": max_descent,
        "max_bitmap_bytes": max((g["width"] * g["height"] for g in glyphs), default=0),
        "px_size": px_size,
    }


def verify_vlw_binary(name: str, blob: bytes, expected_chars: list[str]) -> dict:
    """
    Byte-by-byte verification replicating LovyanGFX's VLWfont::loadFont()
    and VLWfont::drawChar() seek/read offsets exactly.
    """
    assert len(blob) >= 24, f"{name}: truncated header"
    gCount, version, hdr_yAdv, hdr_space, hdr_asc, hdr_desc = struct.unpack_from(">IIIIII", blob, 0)
    assert version == 11, f"{name}: bad VLW version {version}"
    assert gCount == len(set(expected_chars)), f"{name}: gCount {gCount} != {len(set(expected_chars))}"

    maxAscent = abs(struct.unpack(">i", struct.pack(">I", hdr_asc))[0])
    maxDescent = abs(struct.unpack(">i", struct.pack(">I", hdr_desc))[0])
    bitmapPtr = 24 + gCount * 28

    prev_cp = -1
    seen = set()
    non_space_checked = 0

    for gNum in range(gCount):
        off = 24 + gNum * 28
        uc, h, w, xAdv, dY, dX, pad = struct.unpack_from(">IIIIiiI", blob, off)
        assert uc > prev_cp, f"{name}: gUnicode NOT strictly sorted at index {gNum} ({uc:#x} <= {prev_cp:#x})"
        prev_cp = uc
        seen.add(uc)

        # Verify LovyanGFX's uint8/int8 casts don't truncate
        assert 0 <= uc <= 0xFFFF
        assert 0 <= w <= 255
        assert 0 <= xAdv <= 255
        assert -128 <= dX <= 127
        assert pad == 0

        # Verify exact drawChar() offset 28 + gNum*28 reads (h, w, xAdv, dY, dX, pad)
        dc_h, dc_w, dc_xAdv, dc_dY, dc_dX, dc_pad = struct.unpack_from(">IIIiiI", blob, 28 + gNum * 28)
        assert (dc_h, dc_w, dc_xAdv, dc_dY, dc_dX, dc_pad) == (h, w, xAdv, dY, dX, pad)

        if uc == 0x20:
            # Verify drawChar() space shortcut reads xAdvance at 36 + gNum*28
            sp_adv, = struct.unpack_from(">I", blob, 36 + gNum * 28)
            assert sp_adv == xAdv and sp_adv > 0
            assert w == 0 and h == 0
        else:
            assert w > 0 and h > 0, f"{name}: glyph U+{uc:04X} has zero dimension"
            bmp = blob[bitmapPtr : bitmapPtr + w * h]
            assert len(bmp) == w * h, f"{name}: truncated bitmap for U+{uc:04X}"
            assert max(bmp) > 0, f"{name}: all-zero alpha bitmap for U+{uc:04X}"
            non_space_checked += 1

        # Replicate LGFX loadFont maxAscent/maxDescent update
        if (uc > 0xFF) or ((uc > 0x20) and (uc < 0xA0) and (uc != 0x7F)):
            if maxAscent < dY and uc != 0x3000:
                maxAscent = dY
            if maxDescent < (h - dY) and uc != 0x3000:
                maxDescent = h - dY

        # Ensure NO glyph (including 0xA0..0xFF like °, ÄÖÜ) overflows top/bottom of line box!
        yoffset = maxAscent - dY
        assert yoffset >= 0, f"{name}: glyph U+{uc:04X} negative yoffset={yoffset} (maxAscent={maxAscent}, dY={dY})"
        assert yoffset + h <= maxAscent + maxDescent, (
            f"{name}: glyph U+{uc:04X} bottom {yoffset + h} > yAdvance {maxAscent + maxDescent}"
        )

        bitmapPtr += w * h

    assert bitmapPtr == len(blob), f"{name}: exact total length mismatch ({bitmapPtr} != {len(blob)})"
    assert seen == set(ord(c) for c in expected_chars), f"{name}: glyph set mismatch"
    yAdvance = maxAscent + maxDescent
    assert yAdvance == hdr_yAdv, f"{name}: yAdvance mismatch ({yAdvance} != {hdr_yAdv})"
    return {
        "gCount": gCount,
        "yAdvance": yAdvance,
        "maxAscent": maxAscent,
        "maxDescent": maxDescent,
        "bytes": len(blob),
        "non_space_checked": non_space_checked,
    }


def generate_ui_fonts(header_path: Path) -> list[dict]:
    ascii_print = [chr(c) for c in range(0x20, 0x7F)]
    german_ext = list("°²ÄÖÜäöüß–—•")

    specs = [
        (
            "UI_FONT_HERO_NUM",
            ROBOTO_BOLD,
            72,
            list(" 0123456789-.+%:"),
            True,
            "Giant tabular hero numbers (Speed, Watt, Race hero) — Roboto Bold 72px",
        ),
        (
            "UI_FONT_MED_NUM",
            ROBOTO_BOLD,
            34,
            list(" 0123456789.:-+/%°kmhsABCEGIKMNOPRSTVW"),
            True,
            "Medium tabular KPIs, Battery %, Range, Trip, Mode names, Race timer — Roboto Bold 34px",
        ),
        (
            "UI_FONT_HEADING",
            ROBOTO_BOLD,
            22,
            ascii_print + german_ext,
            True,
            "Headings, buttons, PIN keypad digits, card titles (ASCII + DE umlauts + °) — Roboto Bold 22px",
        ),
        (
            "UI_FONT_BODY",
            ROBOTO_MEDIUM,
            16,
            ascii_print + german_ext,
            False,
            "Labels, settings items, telemetry rows, stats subtitles (ASCII + DE umlauts + °) — Roboto Medium 16px",
        ),
        (
            "UI_FONT_SMALL",
            ROBOTO_MEDIUM,
            12,
            ascii_print + german_ext,
            False,
            "Compact captions, units, badges, chart axes (ASCII + DE umlauts + °) — Roboto Medium 12px",
        ),
    ]

    results = []
    sections = []
    total_bytes = 0

    for sym, ttf, px, chars, tabular, desc in specs:
        built = build_vlw_font(ttf, px, chars, tabular_digits=tabular)
        ver = verify_vlw_binary(sym, built["data"], chars)
        total_bytes += ver["bytes"]
        results.append({"symbol": sym, "px": px, "desc": desc, **built, **ver})

        sections.append(
            f"// {desc}\n"
            f"// Glyphs: {built['gCount']} | Line height (yAdvance): {built['yAdvance']}px "
            f"(ascent={built['ascent']}px, descent={built['descent']}px) | "
            f"Size: {len(built['data'])} bytes ({len(built['data']) / 1024.0:.2f} KB) | "
            f"Max glyph stack: {built['max_bitmap_bytes']} B\n"
            f"#define {sym}_LEN     {len(built['data'])}\n"
            f"#define {sym}_HEIGHT  {built['yAdvance']}\n"
            f"#define {sym}_ASCENT  {built['ascent']}\n"
            f"static const uint8_t {sym}[{sym}_LEN] PROGMEM = {{\n"
            f"{format_c_byte_array(built['data'])}\n"
            f"}};\n"
        )

    header = f"""#pragma once

#include <stdint.h>
#include <stddef.h>
#if defined(ARDUINO)
#include <pgmspace.h>
#elif !defined(PROGMEM)
#define PROGMEM
#endif

// ==============================================================================
// Automotive Anti-Aliased Smooth Fonts (LovyanGFX VLW v11 Binary Format)
// Font Family: Roboto Bold & Roboto Medium (Tabular digits for zero gauge jitter)
// Total Flash Footprint: {total_bytes} bytes ({total_bytes / 1024.0:.2f} KB)
// Generated & byte-verified by tools/generate_assets.py
//
// Usage in LovyanGFX (ESP32-S3 & Native Linux Simulator):
//   _canvas->loadFont(UI_FONT_HERO_NUM);
//   _canvas->drawString("48.6", x, y);
//   _canvas->unloadFont(); // restores default built-in font & frees glyph index
//
// Notes:
//   - UTF-8 is enabled by default in LovyanGFX, so UTF-8 literals like "42°C",
//     "Übersicht", "Größe", "—" work directly with UI_FONT_HEADING/BODY/SMALL.
//   - Prefer passing explicit bg color in setTextColor(fg, bg) when overwriting
//     dynamic values, or clear the rect first for clean alpha blending on gradients.
// ==============================================================================

""" + "\n".join(sections)

    header_path.write_text(header, encoding="utf-8")
    return results


def main():
    logo_info = generate_boot_logo(BOOT_LOGO_H)
    print(
        f"[OK] {BOOT_LOGO_H.relative_to(ROOT)}: {logo_info['width']}x{logo_info['height']} PNG = "
        f"{logo_info['png_bytes']} bytes ({logo_info['png_bytes'] / 1024.0:.2f} KB) "
        f"[header: {logo_info['orig_header_bytes'] / 1024.0:.1f} KB -> {logo_info['new_header_bytes'] / 1024.0:.1f} KB]"
    )

    font_results = generate_ui_fonts(UI_FONTS_H)
    total = sum(r["bytes"] for r in font_results)
    print(f"[OK] {UI_FONTS_H.relative_to(ROOT)}: {len(font_results)} VLW fonts, total = {total} bytes ({total / 1024.0:.2f} KB)")
    for r in font_results:
        print(
            f"     - {r['symbol']:18s} {r['px']:2d}px | yAdv={r['yAdvance']:2d}px "
            f"(asc={r['ascent']:2d}, desc={r['descent']:2d}) | glyphs={r['gCount']:3d} | "
            f"size={r['bytes']:6d} B ({r['bytes'] / 1024.0:5.2f} KB) | maxStack={r['max_bitmap_bytes']} B"
        )


if __name__ == "__main__":
    main()
